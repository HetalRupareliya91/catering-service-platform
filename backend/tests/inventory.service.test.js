const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'catering-inventory-'));
const service = require('../src/services/inventory.service');

test('inventory service supports create, read, update and delete', () => {
  const created = service.create({ "item": "Sample item", "quantity": 10, "unit": "Sample unit", "reorderLevel": 10 });
  assert.ok(created.id);
  assert.strictEqual(service.get(created.id).id, created.id);
  assert.strictEqual(service.list().length, 1);
  assert.ok(service.update(created.id, {}));
  assert.ok(service.remove(created.id));
  assert.strictEqual(service.get(created.id), null);
});
