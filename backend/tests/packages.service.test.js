const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'catering-packages-'));
const service = require('../src/services/packages.service');

test('packages service supports create, read, update and delete', () => {
  const created = service.create({ "name": "Sample name", "pricePerPlate": 10, "minGuests": 10, "includes": "Sample includes" });
  assert.ok(created.id);
  assert.strictEqual(service.get(created.id).id, created.id);
  assert.strictEqual(service.list().length, 1);
  assert.ok(service.update(created.id, {}));
  assert.ok(service.remove(created.id));
  assert.strictEqual(service.get(created.id), null);
});
